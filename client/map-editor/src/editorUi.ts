function camelCaseToText(str: string) {
    return str
        .replace(/([A-Z])/g, " $1")
        .split(" ")
        .map((s) => {
            return `${s.charAt(0).toUpperCase()}${s.substring(1)}`;
        })
        .join(" ");
}

const MIN_ZOOM = 0.2;
const MAX_ZOOM = 12;
const ZOOM_STEP = 0.2;

/** Every `MapObjectDefs` type that can be placed as a top level entry. */
export function placeableObjectTypes() {
    return MapObjectDefs.getAllTypes().filter((type) => {
        const def = MapObjectDefs.typeToDefSafe(type);
        if (!def) return false;
        // loot spawners roll random loot tables; not meaningful to author
        if (def.type === "loot_spawner") return false;
        // walls are generated by buildings, too many to list
        if (def.type === "obstacle" && def.isWall) return false;
        return true;
    });
}

interface MapParams {
    mapName: string;
    seed: string;
    width: number;
    height: number;
    shoreInset: number;
    grassInset: number;
    placeName: string;
    removeRiverIndex: string;
}

/** A cached string that a tweakpane monitor binds to. */
interface TextMonitor {
    text: string;
}

export class EditorUi {
    pane: Pane;
    docsPane: Pane;

    /** Retained so the per-frame update can refresh them without a full pane refresh. */
    private zoomBind!: ReturnType<Pane["addBinding"]>;
    private cursorBind!: ReturnType<Pane["addBinding"]>;

    private mapParams!: MapParams;
    /** Cached monitor values; tweakpane reads them each frame. */
    private riverSummary: TextMonitor = { text: "none (max 8)" };
    private placeSummary: TextMonitor = { text: "none (max 8)" };
    /** Change detection so the pane is only re-read when something moved. */
    private lastParamsKey = "";

    constructor(
        public config: ConfigManager,
        public display: EditorDisplay,
        public ctx: EditorContext,
        public tools: EditorTools,
    ) {
        const container = document.getElementById("editor-ui") as HTMLDivElement;

        this.pane = new Pane({
            container,
            expanded: true,
            title: "Map Editor",
        });

        this.docsPane = new Pane({
            container: document.getElementById("editor-side-ui") as HTMLDivElement,
            expanded: true,
            title: "Document",
        });

        this.buildDocumentSection();
        this.buildCameraSection();
        this.buildToolsSection();
        this.buildMapSection();
        this.buildRendererSection();
    }

    //
    // Document actions (right hand pane)
    //

    private buildDocumentSection() {
        const ctx = this.ctx;
        const folder = this.docsPane;

        folder.addButton({ title: "Export JSON" }).on("click", () => ctx.exportDoc());
        folder.addButton({ title: "Import JSON" }).on("click", () => {
            const input = document.getElementById("map-editor-file") as HTMLInputElement | null;
            input?.click();
        });
        folder.addButton({ title: "Load server map" }).on("click", async () => {
            const url = window.prompt(
                "Map capture URL (written by the server's capture-map tool)",
                "maps/main.json",
            );
            if (!url) return;
            try {
                await ctx.loadMapDataUrl(url);
                this.refreshMapParams();
                ctx.onNotice(`Loaded ${url}`);
            } catch (e) {
                console.error(e);
                ctx.onNotice(`Failed to load ${url}`);
            }
        });
        folder.addButton({ title: "Reset document" }).on("click", () => {
            ctx.resetDoc();
            this.refreshMapParams();
        });

        // Minimap preview
        const minimapFolder = folder.addFolder({ title: "Minimap", expanded: false });
        minimapFolder.addButton({ title: "Open minimap (PNG)" }).on("click", () => {
            this.openMinimap();
        });

        // The file picker must not be created inside a folder: `pane.refresh()`
        // can rebuild the DOM and, with it, the listener. It lives in
        // `index.html` and is wired once here.
        const input = document.getElementById("map-editor-file") as HTMLInputElement | null;
        if (!input) {
            console.warn("[map-editor] missing #map-editor-file input");
            return;
        }
        input.addEventListener("change", async () => {
            const file = input.files?.[0];
            if (!file) return;
            try {
                const text = await file.text();
                ctx.loadDoc(parseDocJson(text, ctx.doc.mapName));
                this.refreshMapParams();
                ctx.onNotice(`Imported ${file.name}`);
            } catch (e) {
                console.error(e);
                ctx.onNotice("Failed to import document");
            }
            input.value = "";
        });
    }

    //
    // Camera
    //

    private buildCameraSection() {
        const pane = this.pane;
        const params = this.config.get("mapEditor")!;

        this.zoomBind = pane.addBinding(params, "zoom", {
            label: "Zoom",
            min: MIN_ZOOM,
            max: MAX_ZOOM,
            step: ZOOM_STEP,
        });
        this.zoomBind.on("change", () => {
            this.config.set("mapEditor", params);
        });

        const mapCenter = v2.create(
            this.display.map.width / 2,
            this.display.map.height / 2,
        );

        const posBind = pane.addBinding(params, "pos", {
            x: {
                min: -mapCenter.x,
                max: mapCenter.x,
                step: 0.1,
            },
            y: {
                inverted: true,
                min: -mapCenter.y,
                max: mapCenter.y,
                step: 0.1,
            },
            picker: "inline",
            label: "Camera Position",
        });

        const visualBind = {
            pos: v2.create(0, 0),
        };
        const mousePosBind = pane.addBinding(visualBind, "pos", {
            // Read-only-ish: the pane only mirrors where the cursor is in map
            // space, editing it would fight the mouse handler below.
            x: {
                min: -mapCenter.x,
                max: mapCenter.x,
                step: 0.1,
            },
            y: {
                inverted: true,
                min: -mapCenter.y,
                max: mapCenter.y,
                step: 0.1,
            },
            label: "Cursor Position",
        });
        this.cursorBind = mousePosBind;

        posBind.on("change", (v) => {
            this.display.setPlayerPos(this.display.toWorldPos(v.value));
            this.config.set("mapEditor", params);
        });

        const canvas = this.display.pixi.view as HTMLCanvasElement;
        canvas.addEventListener("mousemove", (e: MouseEvent) => {
            if (e.buttons === 2) {
                // right mouse drag pans the camera
                canvas.style.cursor = "grabbing";
                const delta = v2.div(
                    v2.create(e.movementX, -e.movementY),
                    this.display.camera.m_z(),
                );
                const pos = v2.sub(this.display.activePlayer.m_pos, delta);

                pos.x = Math.round(pos.x * 10) / 10;
                pos.y = Math.round(pos.y * 10) / 10;

                this.display.setPlayerPos(pos);
                params.pos = this.display.toBuildingPos(pos);
                this.config.set("mapEditor", params);
                posBind.refresh();
            } else {
                canvas.style.cursor = "crosshair";
            }

            visualBind.pos = this.display.toBuildingPos(
                this.display.camera.m_screenToPoint(v2.create(e.clientX, e.clientY)),
            );
            mousePosBind.refresh();
        });

        // Right mouse drag pans; suppress the browser menu it would otherwise open
        canvas.addEventListener("contextmenu", (e: MouseEvent) => {
            e.preventDefault();
        });

        const focus = pane.addButton({ title: "Jump to selection" });
        focus.on("click", () => this.ctx.focusSelection());
    }

    //
    // Tools
    //

    private buildToolsSection() {
        const pane = this.pane;
        const params = this.config.get("mapEditor")!;

        const folder = pane.addFolder({ title: "Tools", expanded: true });

        const availableObjects = placeableObjectTypes();

        const objectBind = folder.addBinding(params, "object", {
            label: "Object",
        });
        const objectInput = objectBind.element.querySelector("input") as HTMLInputElement;

        // don't want to trigger keybinds (like L to fullscreen) while typing
        objectInput.addEventListener("keyup", (e) => e.stopPropagation());
        objectInput.addEventListener("keydown", (e) => {
            e.stopPropagation();
            if (e.key === "Enter" && availableObjects.includes(objectInput.value)) {
                params.object = objectInput.value;
                this.config.set("mapEditor", params);
            }
        });

        const dataList = document.createElement("datalist");
        dataList.id = "map-editor-object-list";
        objectInput.setAttribute("list", dataList.id);
        objectInput.parentElement?.appendChild(dataList);
        for (const type of availableObjects) {
            const opt = document.createElement("option");
            opt.value = type;
            dataList.appendChild(opt);
        }

        folder.addBinding(params, "ori", {
            label: "Orientation",
            min: 0,
            max: 3,
            step: 1,
        }).on("change", () => {
            this.config.set("mapEditor", params);
        });

        folder.addButton({ title: "Place at cursor (P)" }).on("click", () => {
            this.placeAtCursor();
        });

        // Layer
        folder.addBinding(params, "layer", {
            label: "Layer",
            options: { Ground: 0, Underground: 1 },
        }).on("change", () => {
            this.config.set("mapEditor", params);
            this.display.setLayer(params.layer);
            this.display.updatePlayer();
        });

        // Selection actions
        const selectionFolder = folder.addFolder({
            title: "Selection",
            expanded: true,
        });

        selectionFolder.addButton({ title: "Rotate 90 (R)" }).on("click", () => {
            this.ctx.rotateSelection(1);
        });
        selectionFolder.addButton({ title: "Flip 180 (F)" }).on("click", () => {
            this.ctx.flipSelection();
        });
        selectionFolder.addButton({ title: "Scale +" }).on("click", () => {
            this.ctx.scaleSelection(1.1);
        });
        selectionFolder.addButton({ title: "Scale -" }).on("click", () => {
            this.ctx.scaleSelection(1 / 1.1);
        });
        selectionFolder.addButton({ title: "Duplicate" }).on("click", () => {
            this.ctx.duplicateSelection();
        });
        selectionFolder.addButton({ title: "Copy" }).on("click", () => {
            this.ctx.copySelection();
        });
        selectionFolder.addButton({ title: "Paste" }).on("click", () => {
            this.ctx.pasteClipboard();
        });
        selectionFolder.addButton({ title: "Delete" }).on("click", () => {
            this.ctx.deleteSelection();
        });
        selectionFolder.addButton({ title: "Deselect" }).on("click", () => {
            this.ctx.setSelection([]);
        });

        // History
        const historyFolder = folder.addFolder({ title: "History", expanded: true });
        historyFolder.addButton({ title: "Undo (Ctrl+Z)" }).on("click", () => this.ctx.undo());
        historyFolder.addButton({ title: "Redo (Ctrl+Y)" }).on("click", () => this.ctx.redo());
    }

    /** Places the currently selected object at the cursor, as one undo step. */
    placeAtCursor() {
        const params = this.config.get("mapEditor")!;
        if (!params.object || !MapObjectDefs.typeExists(params.object)) {
            this.ctx.onNotice(`Unknown object type "${params.object}"`);
            return;
        }
        if (this.ctx.doc.objects.length >= MAP_DOC_LIMITS.maxObjects) {
            this.ctx.onNotice("Document object limit reached");
            return;
        }

        const pos = this.ctx.cursor;
        this.ctx.addEntry({
            type: params.object,
            pos: {
                x: Math.round(pos.x * 10) / 10,
                y: Math.round(pos.y * 10) / 10,
            },
            ori: params.ori,
            scale: 1,
            layer: params.layer,
        });
    }

    //
    // Map parameters
    //

    private buildMapSection() {
        const ctx = this.ctx;
        const folder = this.pane.addFolder({ title: "Map", expanded: false });

        const maps = Object.keys(MapDefs).reduce(
            (a, key) => {
                a[key] = key;
                return a;
            },
            {} as Record<string, string>,
        );

        const riverOptions = Array.from({ length: MAP_DOC_LIMITS.maxRivers }, (_v, i) => String(i))
            .reduce((a: Record<string, string>, i) => {
                a[i] = i;
                return a;
            }, {});

        this.mapParams = {
            mapName: ctx.doc.mapName,
            seed: String(ctx.doc.seed),
            width: ctx.doc.width,
            height: ctx.doc.height,
            shoreInset: ctx.doc.shoreInset,
            grassInset: ctx.doc.grassInset,
            placeName: "",
            removeRiverIndex: "0",
        };
        const params = this.mapParams;

        folder.addBinding(params, "mapName", {
            options: maps,
            label: "Biome",
        }).on("change", (e) => {
            ctx.setMapName(e.value);
            this.refreshMapParams();
        });

        folder.addBinding(params, "width", {
            label: "Width",
            min: MAP_DOC_LIMITS.minSize,
            max: 4096,
            step: 8,
        });
        folder.addBinding(params, "height", {
            label: "Height",
            min: MAP_DOC_LIMITS.minSize,
            max: 4096,
            step: 8,
        });
        folder.addButton({ title: "Apply size" }).on("click", () => {
            ctx.setMapParam("width", Math.round(params.width));
            ctx.setMapParam("height", Math.round(params.height));
            this.refreshMapParams();
        });

        folder.addBinding(params, "shoreInset", {
            label: "Shore Inset",
            min: 0,
            max: 512,
            step: 1,
        });
        folder.addBinding(params, "grassInset", {
            label: "Grass Inset",
            min: 0,
            max: 512,
            step: 1,
        });
        folder.addButton({ title: "Apply insets" }).on("click", () => {
            ctx.setMapParam("shoreInset", Math.round(params.shoreInset));
            ctx.setMapParam("grassInset", Math.round(params.grassInset));
            this.refreshMapParams();
        });

        folder.addBinding(params, "seed", { label: "Seed" }).on("change", (e) => {
            ctx.setSeedFromInput(e.value);
            this.refreshMapParams();
        });
        folder.addButton({ title: "Randomize seed" }).on("click", () => {
            ctx.randomSeed();
            this.refreshMapParams();
        });

        // Rivers
        const riverFolder = folder.addFolder({ title: "Rivers", expanded: false });
        // Live read-only summary. Tweakpane 4 has no `addMonitor`, so this is a
        // readonly text binding with a manual ticker (`interval: 0`), re-read by
        // `refreshMapParams()`. It must stay a *binding*: a monitor controller
        // has no `api`, so `Pane.refresh()` would throw on it.
        riverFolder.addBinding(this.riverSummary, "text", {
            label: "Rivers",
            readonly: true,
            interval: 0,
        });

        riverFolder.addButton({ title: "Add river" }).on("click", () => {
            ctx.addRiver();
            this.refreshMapParams();
        });
        riverFolder.addBinding(params, "removeRiverIndex", {
            label: "Remove river #",
            options: riverOptions,
        });
        riverFolder.addButton({ title: "Remove" }).on("click", () => {
            const index = Number.parseInt(params.removeRiverIndex, 10);
            if (Number.isFinite(index) && ctx.doc.rivers[index]) {
                ctx.removeRiver(index);
                this.refreshMapParams();
            }
        });

        // Places
        const placeFolder = folder.addFolder({ title: "Places", expanded: false });
        // Same readonly-binding trick as the river summary above.
        placeFolder.addBinding(this.placeSummary, "text", {
            label: "Places",
            readonly: true,
            interval: 0,
        });
        placeFolder.addBinding(params, "placeName", { label: "Name" });
        placeFolder.addButton({ title: "Add place at cursor" }).on("click", () => {
            ctx.addPlace(params.placeName, ctx.cursor);
            params.placeName = "";
            this.refreshMapParams();
        });
        placeFolder.addButton({ title: "Remove last place" }).on("click", () => {
            if (ctx.doc.places.length) {
                ctx.removePlace(ctx.doc.places.length - 1);
                this.refreshMapParams();
            }
        });
    }

    /**
     * Pulls the live document values back into the pane's cached params.
     *
     * `normalizeDoc` clamps the arrays to the `MapMsg` wire caps, so the counts
     * shown here are what an export would actually contain.
     */
    refreshMapParams() {
        const doc = this.ctx.doc;

        const params = this.mapParams;
        params.mapName = doc.mapName;
        params.seed = String(doc.seed);
        params.width = doc.width;
        params.height = doc.height;
        params.shoreInset = doc.shoreInset;
        params.grassInset = doc.grassInset;

        // Keep the "remove river #" picker honest: only real indices
        if (Number.parseInt(params.removeRiverIndex, 10) >= doc.rivers.length) {
            params.removeRiverIndex = "0";
        }

        this.riverSummary.text = !doc.rivers.length
            ? "none (max 8)"
            : doc.rivers
                .map((river, i) => {
                    return `#${i} w${river.width}${river.looped ? " loop" : ""}`;
                })
                .join(" · ");
        this.placeSummary.text = !doc.places.length
            ? "none (max 8)"
            : doc.places.map((place) => place.name || "(unnamed)").join(" · ");

        // Bindings read their object on refresh, so re-read the whole pane.
        this.pane.refresh();
        this.docsPane.refresh();
    }

    //
    // Renderer
    //

    private buildRendererSection() {
        const params = this.config.get("mapEditor")!;
        const rendererParams = this.config.get("debugRenderer")!;

        const folder = this.pane.addFolder({ title: "Renderer", expanded: false });

        folder.addBinding(params, "hideCeilings", { label: "Hide Ceilings" }).on("change", () => {
            this.config.set("mapEditor", params);
        });
        folder.addBinding(params, "showGrid", { label: "Show Grid" }).on("change", () => {
            this.config.set("mapEditor", params);
        });
        folder.addBinding(params, "showBounds", { label: "Show Bounds" }).on("change", () => {
            this.config.set("mapEditor", params);
        });

        const addObject = (
            defaultObj: Record<string, unknown>,
            outObj: Record<string, unknown>,
            parentObj: Record<string, unknown>,
            target: FolderApi | TabPageApi,
            configKey: ConfigKey,
        ) => {
            for (const key in defaultObj) {
                const entry = defaultObj[key];
                if (typeof entry === "object") {
                    const folder2 = target.addFolder({
                        title: camelCaseToText(key),
                        expanded: true,
                    });
                    addObject(
                        entry as Record<string, unknown>,
                        outObj[key] as Record<string, unknown>,
                        parentObj,
                        folder2,
                        configKey,
                    );
                } else if (typeof entry === "boolean") {
                    const label = key === "enabled" ? "All debug lines" : camelCaseToText(key);
                    const bind = target.addBinding(outObj, key, { label });
                    bind.on("change", () => {
                        this.config.set(configKey, parentObj as ConfigType[ConfigKey]);
                    });
                }
            }
        };
        addObject(debugRendererConfig, rendererParams, rendererParams, folder, "debugRenderer");
    }

    /**
     * Renders `Map.renderMap` into a texture and opens the PNG in a new tab.
     *
     * `renderMap` draws the terrain plus the objects collected in
     * `map.mapData.objects` (the minimap marker list, i.e. `def.map.display` at
     * layer 0). The editor replay does not fill that array, so it is populated
     * from the derived `MapMsg` first and restored afterwards.
     */
    openMinimap() {
        const display = this.display;
        const msg = this.ctx.getMapMsg();

        const prevObjects = display.map.mapData.objects;
        const prevPlaces = display.map.mapData.places;
        display.map.mapData.objects = msg.objects;
        display.map.mapData.places = msg.places;

        display.map.renderMap(display.pixi.renderer as PIXI.IRenderer, display.canvasMode);
        display.map.mapData.objects = prevObjects;
        display.map.mapData.places = prevPlaces;

        const texture = display.map.getMapTexture();
        if (!texture) {
            this.ctx.onNotice("Minimap render failed");
            return;
        }

        const canvas = display.pixi.renderer.extract.canvas(texture) as HTMLCanvasElement;
        canvas.toBlob?.((blob) => {
            if (blob) window.open(URL.createObjectURL(blob));
        });
    }

    //
    // Per frame
    //

    m_update(input: InputHandler) {
        this.updateZoom(input);
        this.updateStatus();

        // The document can change without the map pane being responsible for it
        // (tools, undo/redo), so keep the cached pane values in sync — but only
        // when a value actually moved, otherwise the whole panel would
        // re-render every frame.
        const key = this.mapParamsKey();
        if (key !== this.lastParamsKey) {
            this.lastParamsKey = key;
            this.refreshMapParams();
        }
    }

    private updateZoom(input: InputHandler) {
        const params = this.config.get("mapEditor")!;
        let zoom = params.zoom;

        if (input.mouseWheelState === MouseWheel.Down) {
            zoom += ZOOM_STEP;
        }
        if (input.mouseWheelState === MouseWheel.Up) {
            zoom -= ZOOM_STEP;
        }

        zoom = math.clamp(zoom, MIN_ZOOM, MAX_ZOOM);
        if (zoom !== params.zoom) {
            params.zoom = zoom;
            this.zoomBind.refresh();
            this.config.set("mapEditor", params);
        }

        this.config.config.debugRenderer = this.config.get("debugRenderer")!;
    }

    private updateStatus() {
        const summary = summarize(this.ctx.doc);

        // Hover wins: with hundreds of similar looking obstacles the only way to
        // tell them apart in the editor is to say what is under the cursor.
        const hover = this.ctx.getHover?.();
        const hoverText = hover ? `hover: ${hover.type}` : "";

        if (summary.objects === 0) {
            this.tools.status = hoverText
                ? `${hoverText} · empty document — pick an object, press P`
                : "Empty document — pick an object, press P";
            return;
        }

        const top = summary.objectCounts[0];
        const counts = `${summary.objects} object(s), ${summary.objectCounts.length} type(s)`
            + ` · most: ${top[0]} x${top[1]}`;
        this.tools.status = hoverText ? `${counts} · ${hoverText}` : counts;
    }

    /**
     * Change key for everything the "Map" pane displays. River/place *content*
     * matters too (names and widths), not just the counts.
     */
    private mapParamsKey() {
        const p = this.mapParams;
        return [
            p.mapName,
            p.seed,
            p.width,
            p.height,
            p.shoreInset,
            p.grassInset,
            p.removeRiverIndex,
            this.ctx.doc.rivers
                .map((river) => `${river.width}:${river.looped ? 1 : 0}:${river.points.length}`)
                .join(","),
            this.ctx.doc.places.map((place) => place.name).join(","),
        ].join("|");
    }
}
