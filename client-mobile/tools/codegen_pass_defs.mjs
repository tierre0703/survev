// Generates proj.android/app/src/dev/axmol/app/GeneratedPassData.java from the
// real shared/ pass + quest defs. The Java pass screen needs only the data the
// server response does not carry: the per-level XP curve, the level -> item
// unlock table, and each quest's XP reward / timed flag.
//
// Usage: node --experimental-transform-types tools/codegen_pass_defs.mjs
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
const sharedDir = path.resolve(here, "../../shared");
const outFile = path.join(
    here,
    "../proj.android/app/src/dev/axmol/app/GeneratedPassData.java",
);

function pathToFile(dir, rel) {
    return new URL(`file:///${path.join(dir, rel).replace(/\\/g, "/")}`);
}

const { PassDefs } = await import(pathToFile(sharedDir, "defs/gameObjects/passDefs.ts"));
const { QuestDefs } = await import(pathToFile(sharedDir, "defs/gameObjects/questDefs.ts"));
const { passUtil } = await import(pathToFile(sharedDir, "utils/passUtil.ts"));
const { GameObjectDefs } = await import(pathToFile(sharedDir, "defs/register.ts"));

const esc = (s) => String(s ?? "").replace(/\\/g, "\\\\").replace(/"/g, "\\\"");
const str = (s) => `"${esc(s)}"`;
const intArray = (xs) => `new int[]{${xs.map((x) => Number(x) | 0).join(",")}}`;
const stringArray = (xs) => `new String[]{${xs.map((x) => str(x)).join(",")}}`;

// pass.ts setPassUnlockImage needs the item's loadout category (icon/title),
// display name and outfit tint, which the unlock table only stores as a type.
const itemMeta = new Map();
for (const def of Object.values(PassDefs)) {
    for (const entry of def.items) {
        const type = entry.item;
        if (itemMeta.has(type)) {
            continue;
        }
        const itemDef = GameObjectDefs.typeToDefSafe(type);
        const category = itemDef == null
            ? ""
            : itemDef.type === "heal_effect"
            ? "heal"
            : itemDef.type === "boost_effect"
            ? "boost"
            : itemDef.type;
        const tint = itemDef?.type === "outfit" && itemDef.lootImg?.tint != null
            ? itemDef.lootImg.tint
            : 0xffffff;
        itemMeta.set(type, { category, name: itemDef?.name ?? type, tint });
    }
}

let passEntries = "";
for (const [type, def] of Object.entries(PassDefs)) {
    const levels = def.items.map((it) => it.level);
    const items = def.items.map((it) => it.item);
    passEntries += `        PASSES.put(${str(type)}, new PassDef(${str(type)},\n`
        + `                ${intArray(def.xp)},\n`
        + `                ${intArray(levels)},\n`
        + `                ${stringArray(items)}));\n`;
}

let itemEntries = "";
for (const [type, meta] of itemMeta) {
    const tint = `0x${(Number(meta.tint) & 0xffffff).toString(16).toUpperCase().padStart(6, "0")}`;
    itemEntries += `        ITEMS.put(${str(type)}, new ItemDef(${str(type)}, ${str(meta.category)}, `
        + `${str(meta.name)}, ${tint}));\n`;
}

let questEntries = "";
for (const [type, def] of Object.entries(QuestDefs)) {
    questEntries += `        QUESTS.put(${str(type)}, new QuestDef(${str(type)}, ${Number(def.xp) | 0}, `
        + `${def.timed ? "true" : "false"}));\n`;
}

const text = `// Generated by tools/codegen_pass_defs.mjs - do not edit.
// Source: shared/defs/gameObjects/{passDefs,questDefs}.ts + shared/defs/register.ts
package dev.axmol.app;

import java.util.HashMap;
import java.util.Map;

/**
 * Pass/quest data the server response does not include: the per-level XP curve,
 * the level -> item unlock table, the unlock items' loadout metadata (category,
 * tint, display name) and each quest's XP reward / timed flag.
 * Display names come from l10n (\`<pass type>\`, \`<quest type>\`, \`game-<item>\`).
 */
public final class GeneratedPassData {
    private GeneratedPassData() {}

    public static final int PASS_MAX_LEVEL = ${passUtil.getPassMaxLevel()};

    public static final class PassDef {
        public final String type;
        /** XP required for each level, index \`level - 1\`; last value repeats. */
        public final int[] xp;
        /** Sparse item unlock table, parallel to {@link #itemTypes}. */
        public final int[] itemLevels;
        public final String[] itemTypes;

        PassDef(String type, int[] xp, int[] itemLevels, String[] itemTypes) {
            this.type = type;
            this.xp = xp;
            this.itemLevels = itemLevels;
            this.itemTypes = itemTypes;
        }
    }

    /**
     * pass.ts setPassUnlockImage metadata: the loadout category ("outfit",
     * "melee", "emote", "heal", "boost"), the display name and the outfit
     * lootImg tint (0xFFFFFF for everything else).
     */
    public static final class ItemDef {
        public final String type;
        public final String category;
        public final String name;
        public final int tint;

        ItemDef(String type, String category, String name, int tint) {
            this.type = type;
            this.category = category;
            this.name = name;
            this.tint = tint;
        }
    }

    public static final class QuestDef {
        public final String type;
        public final int xp;
        /** Targets are seconds and are shown humanized (pass.ts humanizeTime). */
        public final boolean timed;

        QuestDef(String type, int xp, boolean timed) {
            this.type = type;
            this.xp = xp;
            this.timed = timed;
        }
    }

    private static final Map<String, PassDef> PASSES = new HashMap<String, PassDef>();
    private static final Map<String, QuestDef> QUESTS = new HashMap<String, QuestDef>();
    private static final Map<String, ItemDef> ITEMS = new HashMap<String, ItemDef>();

    static {
${passEntries}${itemEntries}${questEntries}    }

    public static PassDef pass(String type) {
        return PASSES.get(type);
    }

    public static QuestDef quest(String type) {
        return QUESTS.get(type);
    }

    /** Unlock-item metadata for the pass reward art (null for unknown types). */
    public static ItemDef item(String type) {
        return ITEMS.get(type);
    }

    /** passUtil.getPassLevelXp: the last entry repeats past the table. */
    public static int xpForLevel(String type, int level) {
        PassDef def = PASSES.get(type);
        if (def == null || def.xp.length == 0) {
            return 50;
        }
        int idx = Math.max(0, level - 1);
        return idx < def.xp.length ? def.xp[idx] : def.xp[def.xp.length - 1];
    }

    /** pass.ts getNextPassUnlockItemId: "" when that level unlocks nothing. */
    public static String nextUnlockItem(String type, int level) {
        PassDef def = PASSES.get(type);
        if (def == null) {
            return "";
        }
        for (int i = 0; i < def.itemLevels.length; i++) {
            if (def.itemLevels[i] == level + 1) {
                return def.itemTypes[i];
            }
        }
        return "";
    }
}
`;

fs.writeFileSync(outFile, text);
console.log(
    `wrote ${Object.keys(PassDefs).length} pass(es), ${Object.keys(QuestDefs).length} quest(s) -> ${
        path.relative(repoRoot, outFile)
    }`,
);
