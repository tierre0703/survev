// Generates GeneratedMenuData.java from the shared map defs: the Java menu uses
// the web client's splash background for site_info.clientTheme (siteInfo.ts
// `MapDefs[clientTheme].desc.backgroundImg`), and keeps the map's mode icon path
// for the quick-play buttons.
//
// Usage:
//   node --experimental-transform-types tools/codegen_menu_defs.mjs
//
// Output: proj.android/app/src/dev/axmol/app/GeneratedMenuData.java
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const sharedDir = path.resolve(root, "..", "shared");

function pathToFile(dir, rel) {
    return new URL(`file:///${path.join(dir, rel).replace(/\\/g, "/")}`);
}
const { MapDefs } = await import(pathToFile(sharedDir, "defs/mapDefs.ts"));

const esc = (s) => String(s ?? "").replace(/\\/g, "\\\\").replace(/"/g, "\\\"");
const str = (s) => `"${esc(s)}"`;

let rows = "";
for (const [name, def] of Object.entries(MapDefs)) {
    const desc = def?.desc || {};
    const background = desc.backgroundImg || "img/splashes/main.webp";
    const icon = desc.icon || "";
    rows += `        {${str(name)},${str(background)},${str(icon)}},\n`;
}

const out = `// GENERATED by tools/codegen_menu_defs.mjs — do not hand-edit.
package dev.axmol.app;

final class GeneratedMenuData {
    private GeneratedMenuData() {}

    // {mapName, splash background asset, mode icon source path}
    private static final String[][] ENTRIES = {
${rows}    };

    private static String[] entry(String mapName) {
        if (mapName != null) {
            for (String[] row : ENTRIES) {
                if (mapName.equals(row[0])) return row;
            }
        }
        for (String[] row : ENTRIES) {
            if ("main".equals(row[0])) return row;
        }
        return null;
    }

    /** siteInfo.ts: cachedBgImg = MapDefs[clientTheme].desc.backgroundImg. */
    static String background(String theme) {
        String[] row = entry(theme);
        return row != null ? row[1] : "img/splashes/main.webp";
    }

    /** MapDefs[mapName].desc.icon (web mode-button art; may be empty). */
    static String modeIconSource(String mapName) {
        String[] row = entry(mapName);
        return row != null ? row[2] : "";
    }

    /** Rasterized menu icon (tools/build-menu-icons.mjs); "" when the map has none. */
    static String modeIcon(String mapName) {
        return modeIconSource(mapName).isEmpty() ? "" : "img/menu/" + mapName + ".png";
    }
}
`;

fs.writeFileSync(path.resolve(root, "proj.android/app/src/dev/axmol/app/GeneratedMenuData.java"), out);
console.log(`wrote GeneratedMenuData.java (${Object.keys(MapDefs).length} maps)`);
