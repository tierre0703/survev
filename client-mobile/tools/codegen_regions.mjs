// Generates src/net/generatedRegions.inc from the server's `regions` config.
//
// The web build bakes the same table into the bundle as `PING_TEST_URLS`
// (client/vite.config.mts): `getConfig(!isDev, "")` -> `Config.regions` ->
// [{region, zone: region, url: address, https}]. The native client cannot read
// the server's response for this (site_info only lists populations), so it
// generates the probe targets at build time exactly like the web does.
//
// Usage:
//   node --experimental-transform-types tools/codegen_regions.mjs             # dev config
//   node --experimental-transform-types tools/codegen_regions.mjs --production
//
// `--production` reads ./survev-config.hjson (the deployment config), matching
// `vite build`; without it the dev defaults are used (adds the local region).
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
const outFile = path.join(here, "../src/net/generatedRegions.inc");

const isProduction = process.argv.includes("--production");
const { getConfig } = await import(
    new URL(`file:///${path.join(repoRoot, "config.ts").replace(/\\/g, "/")}`)
);
const Config = getConfig(isProduction, "");

const esc = (s) => String(s ?? "").replace(/\\/g, "\\\\").replace(/"/g, "\\\"");
const str = (s) => `"${esc(s)}"`;

let entries = "";
let count = 0;
for (const [region, data] of Object.entries(Config.regions)) {
    if (!data || !data.address) {
        continue;
    }
    // zone === region, like PING_TEST_URLS in the web build.
    entries += `    {${str(region)},${str(region)},${str(data.address)},${data.https ? "true" : "false"}},\n`;
    count++;
}

const text = `// Generated by tools/codegen_regions.mjs - do not edit.
// Source: ${isProduction ? "survev-config.hjson (production)" : "dev config defaults"}
// Mirrors the web build's PING_TEST_URLS (client/vite.config.mts).
// {"region","zone","url","https"}
${entries}`;

fs.writeFileSync(outFile, text);
console.log(`wrote ${count} region(s) -> ${path.relative(repoRoot, outFile)}`);
